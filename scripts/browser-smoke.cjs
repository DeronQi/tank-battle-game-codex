async (page) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(new URL('/', page.url()).href);
  if (!(await page.locator('#setup-screen').isVisible()) || await page.locator('#battle-screen').isVisible()) throw Error('Initial screen must be deployment only');
  await page.locator('[data-mode=duo]').click();
  const state = () => page.evaluate(async () => (await import('/src/main.js')).inspectGame());
  await page.locator('#start').click();
  const before = await state();
  if (await page.locator('#setup-screen').isVisible()) throw Error('Deployment must not remain visible during battle');
  if (await page.locator('#battle-screen .dashboard > *').count() !== 2) throw Error('Battle must contain field and status only');
  if (await page.locator('.controls-panel, .supplies-panel, .daily-tip').count()) throw Error('Help content must live in the manual');
  if (before.players.length !== 2) throw Error('Expected two players');
  if (page.viewportSize().width > 620) {
    const aligned = await page.evaluate(() => {
      const box = s => document.querySelector(s).getBoundingClientRect();
      const header = box('.topbar'), main = box('.dashboard'), game = box('.battle-section'), status = box('.right-column');
      return Math.abs(header.left - main.left) < 1 && Math.abs(header.right - main.right) < 1 && Math.abs(game.top - status.top) < 1 && Math.abs(game.bottom - status.bottom) < 1;
    });
    if (!aligned) throw Error('Header/main width or game/status height must align');
  }
  await page.keyboard.down('w'); await page.keyboard.down('ArrowLeft');
  await page.keyboard.down('Space'); await page.keyboard.down('Enter');
  await page.waitForTimeout(350);
  await page.keyboard.up('w'); await page.keyboard.up('ArrowLeft');
  await page.keyboard.up('Space'); await page.keyboard.up('Enter');
  const moved = await state();
  if (!(moved.players[0].y < before.players[0].y && moved.players[1].x < before.players[1].x)) throw Error('Independent keyboard movement failed');
  await page.keyboard.press('p');
  const paused = await state(); await page.waitForTimeout(220); const still = await state();
  if (!paused.paused || still.time !== paused.time) throw Error('Pause failed');
  await page.keyboard.press('p'); if ((await state()).paused) throw Error('Resume failed');
  await page.locator('#nav-editor').click();
  if (!(await state()).paused) throw Error('Editor must pause combat');
  await page.locator('#editor-clear').click();
  await page.locator('#level-name').fill('浏览器实测关卡');
  const box = await page.locator('#editor-canvas').boundingBox();
  await page.mouse.move(box.x + box.width * 5.5 / 26, box.y + box.height * 7.5 / 26);
  await page.mouse.down(); await page.mouse.move(box.x + box.width * 9.5 / 26, box.y + box.height * 7.5 / 26, { steps: 5 }); await page.mouse.up();
  await page.locator('#editor-save').click();
  let saved = await page.evaluate(() => JSON.parse(localStorage.getItem('sf-level')));
  if (saved.name !== '浏览器实测关卡' || saved.tiles[7][5] !== 1 || saved.tiles[7][9] !== 1) throw Error('Editor painting or save failed');
  await page.locator('#editor-undo').click(); await page.locator('#editor-save').click();
  saved = await page.evaluate(() => JSON.parse(localStorage.getItem('sf-level')));
  if (saved.tiles[7][5] !== 0) throw Error('Editor undo failed');
  await page.locator('#editor-random').click(); await page.locator('#editor-save').click();
  await page.screenshot({ path: 'output/playwright/editor.png' });
  const downloadEvent = page.waitForEvent('download'); await page.locator('#editor-export').click(); const download = await downloadEvent;
  await download.saveAs('output/playwright/exported-level.json');
  await page.locator('#editor-clear').click();
  await page.locator('#import-file').setInputFiles('output/playwright/exported-level.json');
  await page.locator('#editor-play').click();
  if ((await state()).status !== 'playing') throw Error('Custom map deployment failed');
  await page.locator('#nav-guide').click();
  if (!(await page.locator('#guide-dialog').isVisible()) || !(await state()).paused) throw Error('Guide modal failed');
  await page.locator('#guide-dialog .close-dialog').click();
  if ((await state()).paused) throw Error('Dialog close should resume');
  await page.keyboard.press('p');
  await page.screenshot({ path: 'output/playwright/duo.png' });
  await page.locator('#nav-battle').click();
  const selectionTime = (await state()).time;
  await page.waitForTimeout(200);
  if ((await state()).time !== selectionTime) throw Error('Start screen must freeze the previous battle');
  await page.locator('#return-battle').click();
  if (!(await state()).paused) throw Error('Returning from setup must preserve an existing pause');
  await page.keyboard.press('p');
  await page.locator('#nav-battle').click();
  await page.locator('#return-battle').click();
  if ((await state()).paused) throw Error('Returning from setup must resume a previously running battle');
  await page.locator('#nav-battle').click();
  await page.locator('[data-mode="demo"]').click();
  await page.locator('[data-ai="2"]').click();
  await page.locator('#map-source').selectOption('random');
  await page.locator('#difficulty').selectOption('easy');
  await page.locator('#start').click();
  const ai = await state();
  if (!ai.players.every(p => p.ai) || ai.players.length !== 2) throw Error('Duo AI did not start');
  await page.waitForTimeout(1300);
  await page.screenshot({ path: 'output/playwright/ai.png' });

  if (errors.length) throw Error(errors.join('; '));
  return { keyboard: 'passed', pause: 'passed', editor: 'paint/undo/save/export/import/deploy passed', modal: 'passed', ai: 'two bots started', errors };
}
